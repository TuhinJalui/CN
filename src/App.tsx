import { useEffect, useRef, useState } from 'react'
import { ArrowUpRight, AudioWaveform, Orbit, Play, ShieldCheck, Sparkles, TriangleAlert } from 'lucide-react'
import { useSimulation } from './hooks/useSimulation'
import type { LabMode } from './lib/types'
import { Header } from './components/Header'
import { AirGapStage } from './components/AirGapStage'
import { FskPanel } from './components/FskPanel'
import { SpectrumPanel } from './components/SpectrumPanel'
import { ScopePanel } from './components/ScopePanel'
import { PacketPanel } from './components/PacketPanel'
import { DataFlowPanel, ProtocolStack } from './components/ProtocolPanels'
import { ControlConsole, TelemetryPanel } from './components/RailPanels'
import { ThreeLab } from './components/ThreeLab'
import { HandshakeOverlay } from './components/HandshakeOverlay'
import { InfoModal } from './components/InfoModal'
import { CompletionOverlay } from './components/CompletionOverlay'
import { PresentationChrome } from './components/PresentationChrome'
import { TabletDock } from './components/TabletDock'
import { SectionIntro, Tag, cx } from './components/ui'
import { ExperimentLab } from './modes/ExperimentLab'
import { SignalLab } from './modes/SignalLab'
import { DefenseMode } from './modes/DefenseMode'
import { StegoMode } from './modes/StegoMode'
import { DISCLAIMER } from './content'

function Overview({
  sim,
  onInfo,
  onOpen3D,
  onHandshake,
  onPresent,
}: {
  sim: ReturnType<typeof useSimulation>
  onInfo: (topic: string) => void
  onOpen3D: () => void
  onHandshake: () => void
  onPresent: () => void
}) {
  return (
    <div className="mode-page overview-page">
      <SectionIntro
        kicker="01 / RESEARCH OPERATIONS"
        title={<>The air gap is <span className="title-accent">not silent.</span></>}
        description="A live research instrument for an FSK-based acoustic bridge: build a packet, turn bits into near-ultrasonic tones, watch them cross a physical gap, and verify what the receiver reconstructed."
        right={
          <div className="overview-intro-status">
            <div className="intro-live-line">
              <span className="intro-live-dot" />
              <span>{sim.paused ? 'SIMULATION PAUSED' : sim.running ? 'SIMULATION RUNNING' : 'LABORATORY READY'}</span>
            </div>
            <div className="intro-paper-line">
              <span>NEAR-SOUND COMMUNICATION / FSK ACOUSTIC NETWORK</span>
              <span>ARCHITECTURE MODEL · v0.9</span>
            </div>
            <div className="intro-button-row">
              <button type="button" className="ghost-button compact" onClick={onPresent}>
                <Play size={13} />
                PRESENTATION
              </button>
              <button type="button" className="ghost-button compact" onClick={onOpen3D}>
                <Orbit size={13} />
                3D LAB
              </button>
            </div>
          </div>
        }
      />

      <AirGapStage
        sim={sim}
        onExplain={() => onInfo('airgap')}
        onOpen3D={onOpen3D}
        onHandshake={onHandshake}
      />

      <div className="overview-signal-grid">
        <FskPanel sim={sim} onInfo={() => onInfo('fsk')} />
        <SpectrumPanel sim={sim} onInfo={() => onInfo('fft')} />
      </div>

      <div className="overview-secondary-grid">
        <ScopePanel sim={sim} onInfo={() => onInfo('scope')} />
        <ProtocolStack sim={sim} onInfo={() => onInfo('airgap')} />
      </div>

      <DataFlowPanel sim={sim} onInfo={() => onInfo('crc')} />

      <PacketPanel sim={sim} onInfo={() => onInfo('crc')} />

      <section className="research-boundary-band">
        <div className="boundary-band-head">
          <div>
            <span className="section-kicker">SCIENTIFIC BOUNDARY / READ FIRST</span>
            <h2>Architecture simulation. Not measured evidence.</h2>
          </div>
          <Tag tone="amber">ILLUSTRATIVE</Tag>
        </div>
        <div className="boundary-band-grid">
          <div>
            <span>01</span>
            <strong>Simulated telemetry</strong>
            <p>Every SNR, BER, PER, latency and CRC value is generated by this browser model or set by you.</p>
          </div>
          <div>
            <span>02</span>
            <strong>No paper data reproduced</strong>
            <p>The supplied architecture paper reports no original measured experimental results.</p>
          </div>
          <div>
            <span>03</span>
            <strong>Not universally inaudible</strong>
            <p>18–21 kHz is near-ultrasonic/high-frequency audio. Perception and hardware response vary.</p>
          </div>
          <div>
            <span>04</span>
            <strong>Authorised research only</strong>
            <p>Jamming and covert-channel studies belong in a controlled, explicitly authorised laboratory.</p>
          </div>
        </div>
      </section>

      <div className="page-signature">
        <div className="signature-line" />
        <div className="signature-copy">
          <AudioWaveform size={15} />
          <span>Inspired by “Near-Sound Communication Protocols for Secure Air-Gap Bridging — An FSK-Based Acoustic Network Architecture.”</span>
        </div>
        <div className="signature-tags">
          <Tag tone="cyan">FSK</Tag>
          <Tag tone="violet">FFT</Tag>
          <Tag tone="green">CRC</Tag>
          <Tag tone="neutral">CONCEPTUAL</Tag>
        </div>
      </div>
    </div>
  )
}

export default function App() {
  const sim = useSimulation()
  const [mode, setMode] = useState<LabMode>('overview')
  const [infoTopic, setInfoTopic] = useState<string | null>(null)
  const [threeOpen, setThreeOpen] = useState(false)
  const [handshakeOpen, setHandshakeOpen] = useState(false)
  const [completionOpen, setCompletionOpen] = useState(false)
  const [presentation, setPresentation] = useState(false)
  const shownResultRef = useRef<number | null>(null)
  const startTimerRef = useRef<number | null>(null)

  const openInfo = (topic: string) => setInfoTopic(topic)

  useEffect(() => {
    if (!sim.run || (!sim.paused && sim.terminal === 'idle')) return undefined
    if (sim.terminal !== 'complete' && sim.terminal !== 'failed') return undefined
    if (shownResultRef.current === sim.run.id) return undefined
    shownResultRef.current = sim.run.id
    const timer = window.setTimeout(() => setCompletionOpen(true), 760)
    return () => window.clearTimeout(timer)
  }, [sim.run, sim.terminal, sim.paused])

  useEffect(() => {
    if (!presentation) return undefined
    const handler = (event: KeyboardEvent) => {
      if (event.key === 'Escape' && !completionOpen && !infoTopic) {
        setPresentation(false)
      }
    }
    window.addEventListener('keydown', handler)
    return () => window.removeEventListener('keydown', handler)
  }, [presentation, completionOpen, infoTopic])

  useEffect(() => {
    return () => {
      if (startTimerRef.current) window.clearTimeout(startTimerRef.current)
    }
  }, [])

  const beginTransmission = () => {
    setHandshakeOpen(false)
    if (startTimerRef.current) window.clearTimeout(startTimerRef.current)
    if (sim.running) {
      sim.reset()
      startTimerRef.current = window.setTimeout(() => sim.start(), 100)
      return
    }
    sim.start()
  }

  const enterPresentation = () => {
    setMode('overview')
    setPresentation(true)
    setCompletionOpen(false)
    if (startTimerRef.current) window.clearTimeout(startTimerRef.current)
    if (sim.running) {
      sim.reset()
    }
    startTimerRef.current = window.setTimeout(() => sim.start(), 360)
  }

  const autoDemo = () => {
    enterPresentation()
  }

  const exitPresentation = () => {
    setPresentation(false)
  }

  const changeMode = (nextMode: LabMode) => {
    setMode(nextMode)
    if (presentation) setPresentation(false)
    window.scrollTo({ top: 0, behavior: 'smooth' })
  }

  const retryTransmission = () => {
    setCompletionOpen(false)
    sim.reset()
    startTimerRef.current = window.setTimeout(() => sim.start(), 160)
  }

  const openThree = () => {
    setCompletionOpen(false)
    setThreeOpen(true)
  }

  const showRail = mode === 'overview' || mode === 'signal'

  return (
    <div className={cx('app-shell', presentation && 'is-presentation', showRail && !presentation && 'has-dock')}>
      <div className="ambient-bg" aria-hidden="true">
        <div className="ambient-orb one" />
        <div className="ambient-orb two" />
        <div className="ambient-grid" />
        <div className="ambient-noise" />
        <div className="screen-scanlines" />
      </div>

      <Header mode={mode} onModeChange={changeMode} onPresent={enterPresentation} />

      <div className={cx('app-body', !showRail && 'no-rail')}>
        <main className="main-column">
          {mode === 'overview' && (
            <Overview
              sim={sim}
              onInfo={openInfo}
              onOpen3D={() => setThreeOpen(true)}
              onHandshake={() => setHandshakeOpen(true)}
              onPresent={enterPresentation}
            />
          )}
          {mode === 'signal' && <SignalLab sim={sim} onInfo={openInfo} />}
          {mode === 'experiment' && <ExperimentLab sim={sim} onInfo={() => openInfo('metrics')} />}
          {mode === 'defense' && <DefenseMode sim={sim} onInfo={openInfo} />}
          {mode === 'stego' && <StegoMode sim={sim} onInfo={openInfo} />}
        </main>

        {showRail && (
          <aside className="rail-column">
            <ControlConsole
              sim={sim}
              onAutoDemo={autoDemo}
              onHandshake={() => setHandshakeOpen(true)}
              onOpenMetricsInfo={() => openInfo('metrics')}
            />
            <TelemetryPanel sim={sim} onInfo={() => openInfo('metrics')} />
            <div className="rail-research-note">
              <TriangleAlert size={13} />
              <span>
                The architecture paper is an implementation plan. All values here are <strong>simulated</strong> or
                <strong> user-configured</strong>.
              </span>
            </div>
          </aside>
        )}
      </div>

      <footer className="app-footer">
        <div>
          <span className="footer-brand">AETHER//GAP</span>
          <span>Acoustic air-gap research visualization</span>
        </div>
        <p>{DISCLAIMER}</p>
        <div className="footer-meta">
          <span>FSK-2 / FFT / CRC-16</span>
          <span>SIMULATION BUILD 0.9.4</span>
        </div>
      </footer>

      {showRail && !presentation && <TabletDock sim={sim} />}

      {presentation && <PresentationChrome sim={sim} onExit={exitPresentation} />}

      {presentation && (
        <div className="presentation-mode-tag">
          <Sparkles size={12} />
          RESEARCH DEMO MODE
        </div>
      )}

      <ThreeLab open={threeOpen} sim={sim} onClose={() => setThreeOpen(false)} />

      <HandshakeOverlay
        open={handshakeOpen}
        config={sim.config}
        onClose={() => setHandshakeOpen(false)}
        onBeginPayload={beginTransmission}
      />

      <InfoModal topic={infoTopic} onClose={() => setInfoTopic(null)} />

      <CompletionOverlay
        run={sim.run}
        onClose={() => setCompletionOpen(false)}
        onRetry={retryTransmission}
        onOpen3D={openThree}
      />

      <div className="global-system-strip">
        <span><span className="strip-dot" /> ALL SYSTEMS SIMULATED</span>
        <span className="strip-center">NEAR-SOUND RESEARCH LABORATORY / AUTHORISED USE</span>
        <span className="strip-right"><ShieldCheck size={11} /> NO NETWORK TRANSPORT <ArrowUpRight size={11} /></span>
      </div>
    </div>
  )
}
